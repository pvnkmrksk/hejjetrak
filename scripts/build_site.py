"""Build the static landing page + mdBook manual, then check local links.

Build-time tool only. Python and mdBook are not application dependencies.
Canonical technical reports stay in docs/ and are staged without changing them.
"""
from __future__ import annotations

import argparse
from html.parser import HTMLParser
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parent.parent
REPORTS = (
    "agent-control.md", "architecture.md", "camera-controls.md", "output.md",
    "parity.md", "performance.md", "tracking-performance.md", "ui-design.md",
    "validation.md", "resources.md", "recovery.md", "matrex-vr.md",
)
REPOSITORY = "https://github.com/pvnkmrksk/hejjetrak"


def add_manual_navigation(manual: Path):
    """Keep project links visible in the generated toolbar, including without JS."""
    repository_link = re.compile(
        r'<a href="' + re.escape(REPOSITORY)
        + r'" title="Git repository" aria-label="Git repository">.*?</a>',
        re.DOTALL,
    )
    for page in manual.rglob("*.html"):
        # This is the no-JS sidebar iframe, not a standalone manual chapter.
        if page.name == "toc.html":
            continue
        source = page.read_text()
        if source.count('<div class="right-buttons">') != 1:
            raise SystemExit(f"mdBook toolbar not found in {page.name}; check the pinned template.")
        website = "../" * len(page.relative_to(manual).parts)
        navigation = (
            '<nav class="project-navigation" aria-label="Project">'
            f'<a href="{website}">Website</a>'
            f'<a href="{REPOSITORY}">GitHub</a></nav>'
        )
        source, replacements = repository_link.subn(navigation, source)
        if replacements != 1:
            raise SystemExit(f"mdBook repository link not found in {page.name}; check the pinned template.")
        page.write_text(source)


class Links(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.targets = set()
        self.links = []

    def handle_starttag(self, tag, attrs):
        values = dict(attrs)
        if values.get("id"):
            self.targets.add(values["id"])
        if tag == "a" and values.get("name"):
            self.targets.add(values["name"])
        for attr in ("href", "src", "poster"):
            if values.get(attr):
                self.links.append(values[attr])


def check_links(output: Path, base_path: str):
    documents = {}
    for path in output.rglob("*.html"):
        parser = Links()
        parser.feed(path.read_text())
        documents[path.resolve()] = parser
    errors = []
    checked = 0
    for document, parser in documents.items():
        for href in parser.links:
            url = urlsplit(href)
            if url.scheme or url.netloc:
                continue
            target_path = unquote(url.path)
            if target_path.startswith("/"):
                if not target_path.startswith(base_path):
                    errors.append(f"{document.relative_to(output)}: outside site base: {href}")
                    continue
                candidate = output / target_path[len(base_path):]
            else:
                candidate = document.parent / target_path if target_path else document
            candidate = candidate.resolve()
            if not candidate.is_relative_to(output):
                errors.append(f"{document.relative_to(output)}: escapes output: {href}")
                continue
            if candidate.is_dir():
                candidate /= "index.html"
            if not candidate.exists():
                errors.append(f"{document.relative_to(output)}: missing {href}")
                continue
            checked += 1
            fragment = unquote(url.fragment)
            if fragment and candidate.suffix == ".html" and fragment not in documents.get(candidate, Links()).targets:
                errors.append(f"{document.relative_to(output)}: missing fragment {href}")
    if errors:
        raise SystemExit("Static link checks failed:\n" + "\n".join(sorted(set(errors))))
    print(f"Checked {checked} internal references in {len(documents)} HTML pages.")


def build(output: Path, mdbook: str, url: str):
    output = output.resolve()
    if output == ROOT or output in ROOT.parents or output.is_relative_to(ROOT / "site") or output.is_relative_to(ROOT / "book") or output.is_relative_to(ROOT / "docs"):
        raise SystemExit("Choose a separate build directory, such as /tmp/hejjetrak-site or _site.")
    if output.exists():
        if not (output / ".hejjetrak-site-build").is_file():
            raise SystemExit(f"Refusing to replace an unmarked existing directory: {output}")
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / ".hejjetrak-site-build").write_text("Generated by scripts/build_site.py\n")
    shutil.copytree(ROOT / "site", output, dirs_exist_ok=True)
    (output / ".nojekyll").write_text("")
    with tempfile.TemporaryDirectory(prefix="hejjetrak-manual-") as temporary:
        stage = Path(temporary) / "book"
        shutil.copytree(ROOT / "book", stage)
        for report in REPORTS:
            text = (ROOT / "docs" / report).read_text()
            # The website is a staged view; preserve the source reports verbatim.
            text = text.replace("../vendor/oxideav-h264/HEJJETRAK_PATCHES.md", "https://github.com/pvnkmrksk/hejjetrak/blob/main/vendor/oxideav-h264/HEJJETRAK_PATCHES.md")
            (stage / "src" / report).write_text(text)
        shutil.copytree(ROOT / "docs" / "images", stage / "src" / "images")
        shutil.copytree(ROOT / "docs" / "benchmarks", stage / "src" / "benchmarks")
        # Historical reports are linked from the evidence chapter.
        for report in ("validation-v0.1.md", "validation-v0.2.md"):
            shutil.copy2(ROOT / "docs" / report, stage / "src" / report)
        subprocess.run([mdbook, "build", str(stage), "--dest-dir", str(output / "manual")], check=True)
    add_manual_navigation(output / "manual")
    check_links(output, urlsplit(url).path)
    print(f"Static site: {output}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("--mdbook", default="mdbook")
    parser.add_argument("--url", default="https://pvnkmrksk.github.io/hejjetrak/")
    args = parser.parse_args()
    if not args.url.endswith("/") or urlsplit(args.url).scheme not in ("http", "https"):
        parser.error("--url must be an absolute http(s) site URL ending in /")
    build(args.output, args.mdbook, args.url)


if __name__ == "__main__":
    main()
